/* Generates src/components/logo-art.ts from the client's logo artwork in the
   app's public/img, so the design system can never drift from the mark
   orkaytiles.com actually ships. Re-run it whenever the artwork changes.

   Why data-URIs rather than a file reference: the uploaded design-system
   bundle ships JS, CSS, fonts and tokens — there is no image channel. A
   design built from this DS resolves `/img/logo_orkay.png` against ITS OWN
   origin, where the file does not exist, so the brand mark would 404 in every
   design the agent produces. Inlining is what makes the lockup self-contained.

   Lossless WebP is the smallest encoding that keeps the red bullseye and
   swoosh exact — this is a brand mark, so quality loss is not a trade worth
   making for a few KB. */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const sharp = require('sharp');

const here = dirname(fileURLToPath(import.meta.url));
const pub = resolve(here, '../../public/img');
const out = resolve(here, '../src/components/logo-art.ts');

/* base layer = white clone (red kept), ink layer = dark original — the two the
   host app's zebra pass cross-fades between. Mirrors app/components/Logo.tsx. */
const SOURCES = [
  ['LOGO_WHITE', `${pub}/logo_orkay_white.png`],
  ['LOGO_DARK', `${pub}/logo_orkay.png`],
];

const lines = [];
let total = 0;
for (const [name, path] of SOURCES) {
  const webp = await sharp(path).webp({ lossless: true }).toBuffer();
  const uri = `data:image/webp;base64,${webp.toString('base64')}`;
  total += uri.length;
  lines.push(`export const ${name} =\n  '${uri}';`);
  console.log(`${name}: ${(webp.length / 1024).toFixed(1)} KB → ${(uri.length / 1024).toFixed(1)} KB inlined`);
}

const header = `/* GENERATED by scripts/build-logo-art.mjs — do not edit.
   The client's ORKAY lockup, inlined so the mark travels with the bundle.
   Source: public/img/logo_orkay{,_white}.png in the orkay-z app. */\n\n`;

writeFileSync(out, header + lines.join('\n\n') + '\n', 'utf8');
console.log(`logo-art.ts: ${(total / 1024).toFixed(1)} KB total`);
